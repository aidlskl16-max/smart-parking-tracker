#!/bin/sh
# ↑ אומר למחשב להריץ את הקובץ הזה עם התוכנה sh (שורת פקודה)

# ============================================================
#  סימולציה של מצלמת ה-IoT: שולחת מספר רכב לשרת ב-HTTP POST
#  שימוש:   sh camera/camera.sh 1234567
#  בלי מספר – נשלח מספר אקראי
# ============================================================

# PLATE = המספר שקיבלנו ($1 = הדבר הראשון שנכתב אחרי שם הסקריפט).
# אם לא קיבלנו כלום – shuf מגריל מספר בין 1000000 ל-99999999
PLATE=${1:-$(shuf -i 1000000-99999999 -n 1)}

# מדפיסים על המסך איזה מספר "המצלמה זיהתה"
echo "📷 Camera detected plate: $PLATE"

# curl = תוכנה ששולחת בקשות רשת. כאן:
#   -s       = בשקט (בלי פס התקדמות)
#   -X POST  = בקשה מסוג POST ("תשמור את זה")
#   הכתובת   = ה-API שלנו, דרך Nginx בפורט 8080
#   -H       = אומרים לשרת שהמידע בפורמט JSON
#   -d       = המידע עצמו: {"plate":"1234567"}
curl -s -X POST http://localhost:8080/api/cars \
     -H "Content-Type: application/json" \
     -d "{\"plate\":\"$PLATE\"}"

# מדפיסים שורה ריקה כדי שהתשובה של השרת לא תידבק לשורת הפקודה הבאה
echo
